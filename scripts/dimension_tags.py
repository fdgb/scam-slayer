def _match(text, kwlist):
    return [kw for kw in kwlist if kw in text]


def tag_text(text):
    """返回 (人群列表, 场景列表, 渠道列表)，均为命中的标签名。"""
    text = text or ""
    pops = [name for name, kws in POPULATION.items() if _match(text, kws)]
    scns = [name for name, kws in SCENARIO.items() if _match(text, kws)]
    chns = [name for name, kws in CHANNEL.items() if _match(text, kws)]
    return pops, scns, chns


def fmt_tags(pops, scns, chns, cap=12):
    def j(lst):
        return "、".join(lst[:cap]) if lst else "—"
    return f"人群：{j(pops)} ｜ 场景：{j(scns)} ｜ 渠道：{j(chns)}"
